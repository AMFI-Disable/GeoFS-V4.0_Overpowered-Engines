const assert = require('node:assert/strict');
const fs = require('node:fs');
const { JSDOM } = require('jsdom');
const dom = new JSDOM('<!doctype html><body><div class="geofs-autopilot-bar"></div></body>', {url:'https://beta.geo-fs.com/geofs.php', runScripts:'outside-only'});
const w = dom.window;
const part = {thrust:100, afterBurnerThrust:0, reverseThrust:0, torque:3};
const ac = {parts:{engine:part}, definition:{zeroThrustAltitude:1000,zeroRPMAltitude:2000}, rigidBody:{setAngularVelocity(){}, getAngularVelocity(){return [1,1,1]}}};
w.geofs = {version:'4.0', aircraft:{instance:ac}, animation:{values:{}}};
w.GeoFSV4Core = {state:'ready', initialize(name,fn){fn(); return Promise.resolve();}};
w.GeoFSV4Design = {};
w.eval(fs.readFileSync('overpowered-engines_standalone.user.js','utf8'));
assert.ok(w.document.querySelector('#opModBtn'));
w.toggleOpEngineUI(); assert.equal(w.document.querySelector('#opEngineCard').style.display, 'block');
w.opMultiplier = 2; w.toggleThrustMode(); assert.equal(part.thrust,200); assert.equal(part.afterBurnerThrust,0); assert.equal(part.reverseThrust,0);
w.opMultiplier = 3; w.document.dispatchEvent(new w.CustomEvent('V40_opMultiplierUpdated',{detail:{value:3}})); assert.equal(part.thrust,300);
w.toggleThrustMode(); assert.equal(part.thrust,100); assert.equal(part.afterBurnerThrust,0); assert.equal(part.reverseThrust,0);
w.toggleCeilingMode(); assert.equal(ac.definition.zeroThrustAltitude,3000000); w.toggleCeilingMode(); assert.equal(ac.definition.zeroThrustAltitude,1000); assert.equal(ac.definition.zeroRPMAltitude,2000);
w.toggleSASMode(); assert.equal(part.torque,0); w.toggleSASMode(); assert.equal(part.torque,3);
w.close(); console.log('OP Engines port checks passed');
